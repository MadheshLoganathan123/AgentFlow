from typing import List, Optional

from pydantic import BaseModel, Field

from packages.contracts.base import VersionedBaseModel


class RequirementMatch(BaseModel):
    requirement: str
    is_satisfied: bool
    evidence_or_gap_explanation: str
    candidate_skill_or_exp: Optional[str] = None


class ScoreBreakdown(BaseModel):
    skill_match_score: float = Field(..., ge=0.0, le=100.0)
    seniority_score: float = Field(..., ge=0.0, le=100.0)
    location_mode_score: float = Field(..., ge=0.0, le=100.0)
    salary_alignment_score: Optional[float] = Field(None, ge=0.0, le=100.0)
    work_authorization_score: float = Field(..., ge=0.0, le=100.0)
    recency_score: float = Field(..., ge=0.0, le=100.0)
    composite_score: float = Field(..., ge=0.0, le=100.0)


class MatchExplanation(VersionedBaseModel):
    """
    Explainable match result generated by the Match and Ranking Agent.
    Avoids opaque scores by exposing explicit dimensions, strengths, and gaps.
    """
    candidate_id: str
    job_id: str
    composite_score: float
    score_breakdown: ScoreBreakdown
    strengths: List[str] = Field(default_factory=list)
    gaps: List[str] = Field(default_factory=list)
    uncertainties: List[str] = Field(default_factory=list)
    matched_requirements: List[RequirementMatch] = Field(default_factory=list)
    recommendation: str = Field(..., description="'strong_match', 'potential_match', 'gap_heavy', 'not_recommended'")
    user_decision: Optional[str] = Field(None, description="'shortlisted', 'dismissed', 'saved', 'pending'")

